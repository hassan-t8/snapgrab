const BY_CATEGORY: Record<ToolCategory, LucideIcon> = {
  Image: ImageIcon,
  PDF: FileText,
  Calculators: Calculator,
  Text: Type,
  Generators: Palette,
  Audio: Music,
  Video,
};

export function toolIcon(tool: Pick<Tool, "slug" | "category">): LucideIcon {
  return BY_SLUG[tool.slug] ?? BY_CATEGORY[tool.category];
}

/** Renders a tool's icon; takes the usual lucide props (className, style, …). */
export function ToolIcon({ tool, ...props }: { tool: Pick<Tool, "slug" | "category"> } & ComponentProps<LucideIcon>) {
  return createElement(toolIcon(tool), props);
}
